/** Spread over the past months, stable per person. */
function joinedDate(key: string): string {
  const start = Date.UTC(2026, 1, 1)
  const span = Date.UTC(2026, 8, 20) - start
  return new Date(start + (fnv(`joined:${key}`) % span)).toISOString()
}

export const PEOPLE: readonly Person[] = SEEDS.map((seed) => ({
  ...seed,
  id: uuidFrom(`person:${seed.key}`),
  joined: joinedDate(seed.key),
}))

const BY_ID = new Map(PEOPLE.map((person) => [person.id, person]))

export function personById(id: string): Person | undefined {
  return BY_ID.get(id)
}

const pictureCache = new Map<string, UserPicture[]>()

/** The person in the profile service's shape (`Profile`), the base of their cards. */
export function personProfile(person: Person): Profile {
  return {
    userId: person.id,
    firstName: person.firstName,
    lastName: person.lastName,
    gender: person.gender,
    sexualPreference: person.sexualPreference,
    biography: person.biography,
    interests: toInterestTags(person.interests),
    pictures: personPictures(person),
    createdAt: person.joined,
    updatedAt: person.joined,
  }
}

/** The person's pictures (generated portraits), profile picture first. */
export function personPictures(person: Person): UserPicture[] {
  let pictures = pictureCache.get(person.id)
  if (!pictures) {
    pictures = person.shots.map((variant, index) => ({
      id: uuidFrom(`picture:${person.key}:${variant}`),
      url: portraitDataUrl(person.look, `person:${person.key}`, variant),
      isProfile: index === 0,
    }))
    pictureCache.set(person.id, pictures)
  }
  return pictures.map((picture) => ({ ...picture }))
}
